-- Add dependency_type to projects
ALTER TABLE projects ADD COLUMN dependency_type VARCHAR(32) NOT NULL DEFAULT 'NO_DEPENDENCY';

-- Create subproject_dependencies table for many-to-many prerequisite tracking
CREATE TABLE subproject_dependencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subproject_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    prerequisite_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT uq_subproject_prerequisite UNIQUE(subproject_id, prerequisite_id),
    CONSTRAINT chk_no_self_dependency CHECK (subproject_id != prerequisite_id)
);

CREATE INDEX idx_subproject_deps_sub ON subproject_dependencies(subproject_id);
CREATE INDEX idx_subproject_deps_prereq ON subproject_dependencies(prerequisite_id);
